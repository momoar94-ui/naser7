def build_context_message(case: CaseFile) -> str:
    """پیام کاربر حاوی زمینهٔ پرونده که پیش از هر تسک ارسال می‌شود."""
    if case.is_empty:
        return "توجه: پروندهٔ ساختاریافته‌ای ثبت نشده است؛ صرفاً بر پایهٔ گفتگو عمل کن."
    return case.to_context()
